-- Syllabus uploads move from a lifetime allowance (7, counted down) to a per-term one (3, counted
-- up against the term stored on the row). The row now extends UserOwnedEntity like every other
-- owned table, so student_id stops being the primary key and becomes the owner column, with a
-- surrogate id as the key and a unique constraint keeping it to one row per student.

ALTER TABLE syllabus_upload_quota DROP CONSTRAINT syllabus_upload_quota_pkey;

ALTER TABLE syllabus_upload_quota ADD COLUMN id bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE syllabus_upload_quota ADD CONSTRAINT syllabus_upload_quota_pkey PRIMARY KEY (id);
ALTER TABLE syllabus_upload_quota
    ADD CONSTRAINT uk_syllabus_upload_quota_student UNIQUE (student_id);

-- Existing rows get a null term, which never matches the current term, so every student starts
-- the current term with the full allowance. Their old lifetime count cannot be attributed to any
-- one term.
ALTER TABLE syllabus_upload_quota ADD COLUMN term character varying(64);
ALTER TABLE syllabus_upload_quota ADD COLUMN uploads_used integer NOT NULL DEFAULT 0;
ALTER TABLE syllabus_upload_quota ADD COLUMN created_at timestamp with time zone;

ALTER TABLE syllabus_upload_quota DROP COLUMN remaining_uploads;
